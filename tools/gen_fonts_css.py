"""Regenerate web/public/fonts.css and web/src/data/captionFonts.json (file -> family, Telugu or not) from the repo's
fonts/ folder (run after adding or replacing a caption font).

    venv/bin/python tools/gen_fonts_css.py

The web app's caption preview and the renderer (selection_v2/captions.py, libass fontsdir=fonts) must use the SAME
font files; web/public/fonts is a link to ../../fonts and the family names are read from each file, as libass does.
Prints the fonts that have no Telugu letters (English-only: fine for English words, not for Telugu captions)."""
from __future__ import annotations

from pathlib import Path

import freetype

ROOT = Path(__file__).resolve().parents[1]
HEAD = """/*
 * Caption fonts: GENERATED by tools/gen_fonts_css.py from the repo's fonts/ folder (the SAME .ttf files the renderer
 * gives libass via fontsdir, selection_v2/captions.py), so the editor preview and the burned-in captions use identical
 * glyphs. web/public/fonts is a link to ../../fonts. Font-family names are read from each file, as libass does.
 */
"""


def main() -> int:
    rows, english_only, listing = [], [], []
    for p in sorted((ROOT / "fonts").glob("*.ttf")):
        f = freetype.Face(str(p))
        fam, sty = (f.family_name or b"").decode(), (f.style_name or b"").decode()
        weight = 900 if "Black" in sty else 700 if (f.style_flags & freetype.FT_STYLE_FLAG_BOLD or "Bold" in sty) else 400
        telugu = bool(f.get_char_index(0x0C15))        # క
        if not telugu:
            english_only.append(fam)
        listing.append({"file": p.name, "family": fam, "weight": weight, "telugu": telugu})
        rows.append(f'@font-face {{\n    font-family: "{fam}";\n    font-style: normal;\n    font-weight: {weight};\n'
                    f'    font-display: swap;\n    src: url("/fonts/{p.name}") format("truetype");\n}}')
    (ROOT / "web" / "public" / "fonts.css").write_text(HEAD + "\n".join(rows) + "\n", encoding="utf-8")
    import json
    (ROOT / "web" / "src" / "data" / "captionFonts.json").write_text(json.dumps(listing, indent=1) + "\n", encoding="utf-8")
    print(f"{len(rows)} fonts -> web/public/fonts.css; English-only: {', '.join(english_only) or 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
